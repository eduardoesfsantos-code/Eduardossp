import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createServer} from 'node:net';
import Database from 'better-sqlite3';

const dir=mkdtempSync(path.join(tmpdir(),'obraponto-rect-'));
const dbFile=path.join(dir,'test.sqlite');
const probe=createServer();
await new Promise((resolve,reject)=>{probe.once('error',reject);probe.listen(0,'127.0.0.1',resolve);});
const port=probe.address().port;
await new Promise(resolve=>probe.close(resolve));
const base='http://127.0.0.1:'+port;
const secret='isolated-test-secret-not-for-production-123456789';
const adminEmail='admin@example.test', password='Test-only-Password-123';
const workerEmail='worker@example.test';
const cwd=path.dirname(fileURLToPath(import.meta.url));
const server=spawn(process.execPath,['server.js'],{cwd,env:{...process.env,DB_PATH:dbFile,PORT:String(port),JWT_SECRET:secret,ADMIN_EMAIL:adminEmail,ADMIN_NAME:'Admin Teste',ADMIN_PASSWORD:password,NODE_ENV:'test'},stdio:['ignore','pipe','pipe']});
let logs='',db;
server.stdout.on('data',d=>logs+=d);
server.stderr.on('data',d=>logs+=d);
const call=async(url,token,method='GET',body,expected=200)=>{
 const res=await fetch(base+'/api'+url,{method,headers:{...(token?{Authorization:'Bearer '+token}:{}),...(body?{'Content-Type':'application/json'}:{})},body:body?JSON.stringify(body):undefined});
 assert.equal(res.status,expected,url+' '+(res.status===expected?'':await res.clone().text()));
 if(res.headers.get('content-type')?.includes('application/json'))return res.json();
 return Buffer.from(await res.arrayBuffer());
};
const wait=ms=>new Promise(r=>setTimeout(r,ms));
try{
 let ready=false;
 for(let i=0;i<100;i++){try{if((await fetch(base+'/api/health')).ok){ready=true;break;}}catch{}if(server.exitCode!==null)break;await wait(150);}
 assert.ok(ready,'Servidor não iniciou: '+logs);
 const admin=(await call('/login',null,'POST',{email:adminEmail,password})).token;
 const workerId=(await call('/admin/workers',admin,'POST',{name:'Colaborador Teste',email:workerEmail,password},201)).worker.id;
 const worker=(await call('/login',null,'POST',{email:workerEmail,password})).token;
 const site=(await call('/admin/sites',admin,'POST',{name:'Obra Teste',city:'Cotia'},201)).id;
 const day=new Intl.DateTimeFormat('en-CA',{timeZone:'America/Sao_Paulo',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date(Date.now()-2*86400000));
 const originalAt=day+'T08:00:00-03:00';
 db=new Database(dbFile);db.pragma('foreign_keys=ON');
 const at=new Date(originalAt).toISOString();
 db.prepare('INSERT INTO punches (id,user_id,site_id,day,type,at,created_at) VALUES (?,?,?,?,?,?,?)').run('original-in',workerId,site,day,'in',at,at);
 const before=db.prepare('SELECT * FROM punches WHERE user_id=?').all(workerId);
 const request=async()=> (await call('/worker/requests',worker,'POST',{day,message:'Teste de retificação'},201)).id;
 const route=id=>'/admin/requests/'+id+'/rectification';
 const rid=await request();
 await call(route(rid),worker,'GET',undefined,403);
 const form=await call(route(rid),admin);
 assert.equal(form.originals.length,1);assert.equal(form.editable,true);
 const add={revision:form.revision,action:'add',type:'out',site_id:site,time:'17:00',reason:'Saída esquecida no teste'};
 await call(route(rid),worker,'POST',add,403);
 await call(route(rid),admin,'POST',{...add,time:'07:00'},400);
 const added=(await call(route(rid),admin,'POST',add,201)).rectification;
 await call(route(rid),admin,'POST',add,409);
 assert.deepEqual(db.prepare('SELECT * FROM punches WHERE user_id=?').all(workerId),before);
 assert.throws(()=>db.prepare('UPDATE punch_rectifications SET reason=? WHERE id=?').run('alterado',added.id));
 assert.throws(()=>db.prepare('DELETE FROM punch_rectifications WHERE id=?').run(added.id));
 const report='/admin/report?worker_id='+workerId+'&from='+day+'&to='+day;
 const history='/worker/history?from='+day+'&to='+day;
 let row=(await call(report,admin)).rows[0];
 assert.equal(row.minutes,540);assert.equal(row.rectified,true);assert.equal(row.original_punches.length,1);
 assert.equal((await call(history,worker)).rows[0].minutes,540);
 assert.equal((await call('/worker/requests',worker)).requests.find(r=>r.id===rid).rectified,1);
 const rid2=await request();
 const form2=await call(route(rid2),admin);
 await call(route(rid2),admin,'POST',{revision:'stale',action:'adjust',target_id:added.id,time:'16:00',reason:'Ajuste de teste'},409);
 await call(route(rid2),admin,'POST',{revision:form2.revision,action:'adjust',target_id:added.id,time:'16:00',reason:'Ajuste de teste'},201);
 row=(await call(report,admin)).rows[0];
 assert.equal(row.minutes,480);assert.equal(row.rectifications.length,2);
 const exportPath='/admin/report/export?worker_id='+workerId+'&from='+day+'&to='+day+'&format=';
 const pdf=await call(exportPath+'pdf',admin);
 assert.equal(pdf.subarray(0,5).toString(),'%PDF-');
 const xlsx=await call(exportPath+'xlsx',admin);
 assert.equal(xlsx.subarray(0,2).toString(),'PK');
 const rid3=await request();
 const form3=await call(route(rid3),admin);
 await call(route(rid3),admin,'POST',{revision:form3.revision,action:'void',target_id:added.id,reason:'Desconsideração de teste'},201);
 row=(await call(report,admin)).rows[0];
 assert.equal(row.punches.length,1);assert.equal(row.original_punches.length,1);assert.equal(row.rectifications.length,3);assert.equal(row.status,'Pendente');
 assert.deepEqual(db.prepare('SELECT * FROM punches WHERE user_id=?').all(workerId),before);
 console.log('OK: autorização, sequência, conflito, original preservado, auditoria imutável, sincronização via API, totais, PDF e Excel.');
}finally{
 db?.close();
 if(server.exitCode===null){const exited=new Promise(r=>server.once('exit',r));server.kill();await exited;}
 rmSync(dir,{recursive:true,force:true});
}
